export function biteTime(index: number): number {
  const cycle = Math.floor(index / BITE_CUES.length);
  return cycle * RECORDING_DURATION + BITE_CUES[index % BITE_CUES.length]!;
}

export function biteEnvelope(time: number): number {
  const local = time % RECORDING_DURATION;
  // Open just before the beat, close on the accent. Capture is independent.
  for (const cue of BITE_CUES) {
    const delta = local - cue;
    if (delta >= -0.14 && delta < 0) return (delta + 0.14) / 0.14;
    if (delta >= 0 && delta < 0.11) return 1 - delta / 0.11;
  }
  return 0;
}
